using System.Text.Json;
using Microsoft.AspNetCore.DataProtection;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Shop.Admin.Controllers.Api;
using Shop.Admin.Services;
using Shop.Database.Infrastructure.Persistence;
using Shop.Database.Infrastructure.Persistence.Repositories;
var cs = "Server=localhost;Database=ShopVerify_Media_20261110;Integrated Security=true;TrustServerCertificate=true";
await using var db = new ShopDbContext(new DbContextOptionsBuilder<ShopDbContext>().UseSqlServer(cs).Options);
var storage = new FtpMediaStorage(db, DataProtectionProvider.Create("media-test"));
using var loggerFactory = LoggerFactory.Create(builder => builder.AddConsole().SetMinimumLevel(LogLevel.Debug));
var imageApi = new StoreProductImageApiController(db, storage, loggerFactory.CreateLogger<StoreProductImageApiController>());
var mediaApi = new StoreMediaUploadApiController(db, storage, loggerFactory.CreateLogger<StoreMediaUploadApiController>());
await using var image = File.OpenRead("Shop/wwwroot/content/products/images/main/adjustable-soldering-iron-hn-012-row-012-main.webp");
var imageResult = await imageApi.Upload(12, new FormFile(image, 0, image.Length, "image", "test.webp"), default);
if (imageResult is not OkObjectResult) throw new Exception("Image upload failed: " + JsonSerializer.Serialize(imageResult));
await using var video = File.OpenRead("Shop/wwwroot/content/products/videos/blue-dial-wristwatch-video-01.mp4");
var videoResult = await mediaApi.Upload("product-video", new FormFile(video, 0, video.Length, "file", "test.mp4"), 12, null, null, null, null, default);
if (videoResult is not OkObjectResult) throw new Exception("Video upload failed: " + JsonSerializer.Serialize(videoResult));
var json = await new StoreRuntimeDatasetRepository(db).ReadCatalogJsonAsync(default);
using var doc = JsonDocument.Parse(json!);
var media = doc.RootElement.GetProperty("media").EnumerateArray().Single(x => x.GetProperty("id").GetString() == "product-12");
string main = media.GetProperty("main").GetString()!;
string videoPath = media.GetProperty("videos").EnumerateArray().Last().GetString()!;
if (!File.Exists(Path.Combine("artifacts/media-ftp", main)) || !File.Exists(Path.Combine("artifacts/media-ftp", videoPath))) throw new Exception("Files not found in FTP root");
Console.WriteLine("Image, video, SQL and catalog OK. Main=" + main + " Video=" + videoPath);

var articleKey = await db.Database.SqlQueryRaw<string>("SELECT TOP 1 [ArticleKey] AS [Value] FROM [Mag].[MagazineArticle] ORDER BY [Id]").SingleAsync();
await using var articleFile = File.OpenRead("Shop/wwwroot/content/products/images/main/adjustable-soldering-iron-hn-012-row-012-main.webp");
var articleResult = await mediaApi.Upload("article", new FormFile(articleFile,0,articleFile.Length,"file","test.webp"),null,null,null,null,articleKey,default);
if (articleResult is not OkObjectResult) throw new Exception("Article upload failed");
string articlePath = await db.Database.SqlQuery<string>($"SELECT [HeroImagePath] AS [Value] FROM [Mag].[MagazineArticle] WHERE [ArticleKey]={articleKey} AND [HeroImagePath]=[ContentImagePath]").SingleAsync();
if (!File.Exists(Path.Combine("artifacts/media-ftp",articlePath))) throw new Exception("Article FTP file missing");
await using var countryFile = File.OpenRead("Shop/wwwroot/content/products/images/main/adjustable-soldering-iron-hn-012-row-012-main.webp");
var countryResult = await mediaApi.Upload("country", new FormFile(countryFile,0,countryFile.Length,"file","test.webp"),null,null,null,"IR",null,default);
if (countryResult is not OkObjectResult) throw new Exception("Country upload failed");
string flagPath = await db.Database.SqlQueryRaw<string>("SELECT [FlagPath] AS [Value] FROM [Geo].[Country] WHERE [CountryCode]=N'IR'").SingleAsync();
if (!File.Exists(Path.Combine("artifacts/media-ftp",flagPath))) throw new Exception("Country FTP file missing");
Console.WriteLine("Article and country uploads, SQL links and FTP files OK.");
